-- ==============================================================================
-- RecommendX - Distributed Product Recommendation Engine
-- PostgreSQL Cloud Database Schema (Optimized for Neon PostgreSQL)
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. USERS TABLE
-- Stores authenticated users, profile credentials, and timestamps.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id SERIAL PRIMARY KEY,
    email VARCHAR(255) UNIQUE NOT NULL,
    username VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255),
    role VARCHAR(20) DEFAULT 'user',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);

COMMENT ON TABLE users IS 'Registered users and authentication details';
COMMENT ON COLUMN users.email IS 'Unique email address for user login and notifications';
COMMENT ON COLUMN users.password_hash IS 'Bcrypt hashed password';

-- ------------------------------------------------------------------------------
-- 2. PRODUCTS TABLE
-- Stores catalog items, category classifications, pricing, and JSONB tags.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    price DECIMAL(10, 2) NOT NULL,
    description TEXT,
    tags JSONB DEFAULT '[]'::jsonb,
    image_url VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_created_at ON products(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_tags ON products USING GIN(tags);

COMMENT ON TABLE products IS 'E-commerce product catalog';
COMMENT ON COLUMN products.tags IS 'JSONB array of descriptive tags for content-based filtering';

-- ------------------------------------------------------------------------------
-- 3. USER BEHAVIOR TABLE
-- Captures real-time user event streams (views, clicks, purchases, ratings, carts).
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_behavior (
    id SERIAL PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id INT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL,
    session_id VARCHAR(100),
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_behavior_user_product ON user_behavior(user_id, product_id);
CREATE INDEX IF NOT EXISTS idx_behavior_timestamp ON user_behavior(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_behavior_user_timestamp ON user_behavior(user_id, timestamp DESC);

COMMENT ON TABLE user_behavior IS 'Streaming user event interactions for recommendation models';

-- ------------------------------------------------------------------------------
-- 4. RECOMMENDATIONS TABLE
-- Caches calculated recommendation rankings per user/product pair.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recommendations (
    id SERIAL PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id INT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    score DECIMAL(5, 4) NOT NULL,
    reason VARCHAR(50),
    computed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP,
    UNIQUE(user_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_recommendations_user ON recommendations(user_id);
CREATE INDEX IF NOT EXISTS idx_recommendations_user_score ON recommendations(user_id, score DESC);

COMMENT ON TABLE recommendations IS 'Precomputed and cached recommendations generated by ML algorithms';

